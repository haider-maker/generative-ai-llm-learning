def genngrams(tokens):
    ngrams = [
        (
            tokens[i-N:i],  # Previous words in original order
            tokens[i]       # Target word
        )
        for i in range(N, len(tokens))
    ]
    return ngrams

def collate_batch(batch):
    context, target = [], []
    for context_words, target_word in batch:
        context.append(vocab(context_words))
        target.append(vocab([target_word])[0])
    context = torch.tensor(context, dtype=torch.long)
    target = torch.tensor(target, dtype=torch.long)
    return context, target

def train(dataloader, model, criterion, optimizer,
          number_of_epochs=100):
    loss_history = []
    for epoch in tqdm(range(number_of_epochs)):
        model.train()
        total_loss = 0
        for context, target in dataloader:
            optimizer.zero_grad()
            predicted = model(context)
            loss = criterion(predicted, target)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
        mean_loss = total_loss / len(dataloader)
        loss_history.append(mean_loss)
    return loss_history

class NGramLanguageModeler(nn.Module):

    def __init__(self, vocab_size, embedding_dim, N):
        super().__init__()
        self.N = N
        self.embedding_dim = embedding_dim
        self.embeddings = nn.Embedding(vocab_size, embedding_dim)
        self.linear1 = nn.Linear(N * embedding_dim, 128)
        self.linear2 = nn.Linear(128, vocab_size)

    def forward(self, inputs):
        embeds = self.embeddings(inputs)
        embeds = embeds.reshape(-1, self.N * self.embedding_dim)
        out = F.relu(self.linear1(embeds))
        out = self.linear2(out)

        return out
