def preprocess_string(s):
    s = re.sub(r"[^\w\s]", '', s)
    s = re.sub(r"\s+", '', s)
    s = re.sub(r"\d", '', s)
    return s

def preprocess(words):
    tokens = word_tokenize(words)
    tokens = [preprocess_string(w) for w in tokens]
    return [w.lower() for w in tokens if len(w) != 0 and w not in string.punctuation]

def tokenizetext(nurcery_rhymes):
    tokenized_rhymes = map(tokenizer, [nurcery_rhymes])
    vocab = build_vocab_from_iterator(tokenized_rhymes, specials=["<unk>"])
    vocab.set_default_index(vocab["<unk>"])
    return vocab
